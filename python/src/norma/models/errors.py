# Modified for Norma.
from enum import StrEnum


class ErrorCode(StrEnum):
    """
    Standardized error codes following OPA-style semantic naming.

    Error codes follow the pattern: RESOURCE_ACTION or CATEGORY_DESCRIPTION
    """

    # Authentication & Authorization (1xx pattern in code)
    AUTH_MISSING_KEY = "AUTH_MISSING_KEY"
    AUTH_INVALID_KEY = "AUTH_INVALID_KEY"
    AUTH_INSUFFICIENT_PRIVILEGES = "AUTH_INSUFFICIENT_PRIVILEGES"
    AUTH_MISCONFIGURED = "AUTH_MISCONFIGURED"
    AUTH_UPSTREAM_REJECTED = "AUTH_UPSTREAM_REJECTED"

    # Resource Not Found (2xx pattern)
    RESOURCE_NOT_FOUND = "RESOURCE_NOT_FOUND"  # Generic fallback
    AGENT_NOT_FOUND = "AGENT_NOT_FOUND"
    POLICY_NOT_FOUND = "POLICY_NOT_FOUND"
    RULE_NOT_FOUND = "RULE_NOT_FOUND"
    RULE_VERSION_NOT_FOUND = "RULE_VERSION_NOT_FOUND"
    RULE_BINDING_NOT_FOUND = "RULE_BINDING_NOT_FOUND"
    EVALUATOR_NOT_FOUND = "EVALUATOR_NOT_FOUND"

    # Conflict Errors (3xx pattern)
    AGENT_NAME_CONFLICT = "AGENT_NAME_CONFLICT"
    POLICY_NAME_CONFLICT = "POLICY_NAME_CONFLICT"
    RULE_NAME_CONFLICT = "RULE_NAME_CONFLICT"
    RULE_BINDING_CONFLICT = "RULE_BINDING_CONFLICT"
    EVALUATOR_NAME_CONFLICT = "EVALUATOR_NAME_CONFLICT"
    RULE_IN_USE = "RULE_IN_USE"
    EVALUATOR_IN_USE = "EVALUATOR_IN_USE"
    SCHEMA_INCOMPATIBLE = "SCHEMA_INCOMPATIBLE"

    # Validation Errors (4xx pattern)
    METHOD_NOT_ALLOWED = "METHOD_NOT_ALLOWED"
    VALIDATION_ERROR = "VALIDATION_ERROR"
    INVALID_CONFIG = "INVALID_CONFIG"
    INVALID_SCHEMA = "INVALID_SCHEMA"
    CORRUPTED_DATA = "CORRUPTED_DATA"
    POLICY_RULE_INCOMPATIBLE = "POLICY_RULE_INCOMPATIBLE"
    RULE_BINDING_INCOMPATIBLE = "RULE_BINDING_INCOMPATIBLE"

    # Console controls contract and agent override lifecycle.
    CONTROL_CONTRACT_REQUIRED = "CONTROL_CONTRACT_REQUIRED"
    CONTROL_CONTRACT_DISABLED = "CONTROL_CONTRACT_DISABLED"
    CONTROL_REVISION_CONFLICT = "CONTROL_REVISION_CONFLICT"
    CONTROL_STATE_UNAVAILABLE = "CONTROL_STATE_UNAVAILABLE"

    # Server Errors (5xx pattern)
    DATABASE_ERROR = "DATABASE_ERROR"
    INTERNAL_ERROR = "INTERNAL_ERROR"
    CHECK_FAILED = "CHECK_FAILED"


_PUBLIC_ERROR_NAMES: dict[ErrorCode, str] = {
    ErrorCode.AUTH_INSUFFICIENT_PRIVILEGES: "ACCESS_DENIED",
}


def make_public_error_code(error_code: ErrorCode) -> str:
    """Return the stable public Norma identifier for a Rule-oriented error code."""
    return f"NORMA_{_PUBLIC_ERROR_NAMES.get(error_code, error_code)}"
